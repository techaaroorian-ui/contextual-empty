import { chromium } from 'playwright';
import { mkdir } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import assert from 'node:assert/strict';

// Start the docs server first. Screenshot artifacts are for human review.
const url = process.env.AAR_LAB_URL || 'http://127.0.0.1:5173';
const out = new URL('../visual-artifacts/', import.meta.url);
await mkdir(out, { recursive: true });
const browser = await chromium.launch();
try {
  const page = await browser.newPage({ viewport: { width: 1440, height: 1100 } });
  const errors = [];
  page.on('pageerror', error => errors.push(error.message));
  await page.goto(url);
  await page.getByRole('heading', { name: 'TechAaroorian UI', exact: true }).waitFor();
  await page.getByRole('link', { name: 'Explore Aar Craft →' }).click();
  await page.getByRole('heading', { name: 'Good ideas start here.' }).waitFor();
  const primary = page.getByRole('button', { name: '+ New project', exact: true });
  const background = async locator => {
    await locator.evaluate(async el => {
      await Promise.all(el.getAnimations().map(animation => animation.finished.catch(() => {})));
    });
    return locator.evaluate(el => getComputedStyle(el).backgroundColor);
  };
  const snapshot = async name => {
    await page.evaluate(() => { document.activeElement?.blur(); window.scrollTo(0, 0); });
    await page.screenshot({ path: fileURLToPath(new URL(name, out)), fullPage: true });
  };
  assert.equal(await background(primary), 'rgb(54, 92, 41)');
  await primary.hover();
  await primary.evaluate(async el => { await Promise.all(el.getAnimations().map(a => a.finished)); });
  assert.equal(await primary.evaluate(el => getComputedStyle(el).translate), '0px -1px');
  const bounds = await primary.boundingBox();
  await page.mouse.move(bounds.x + bounds.width / 2, bounds.y + bounds.height / 2);
  await page.mouse.down();
  await primary.evaluate(async el => { await Promise.all(el.getAnimations().map(a => a.finished)); });
  assert.equal(await primary.evaluate(el => getComputedStyle(el).scale), '0.98');
  await page.mouse.up();
  // The press above already created one project. Reset the demo before the next checks.
  await page.reload();
  await primary.waitFor();
  await primary.click();
  await page.getByRole('heading', { name: 'Untitled project 4' }).waitFor();
  await page.getByRole('searchbox').fill('no such project');
  await page.getByRole('heading', { name: 'No matching projects' }).waitFor();
  await page.getByRole('button', { name: 'Clear filters' }).click();
  await snapshot('workbench-light.png');
  await page.getByLabel('Appearance', { exact: true }).selectOption('dark');
  assert.equal(await background(primary), 'rgb(183, 220, 155)');
  await page.getByLabel('Palette', { exact: true }).selectOption('iris');
  assert.equal(await background(primary), 'rgb(209, 187, 255)');
  await page.getByLabel('Compare light & dark').check();
  const previews = page.locator('.preview');
  assert.equal(await previews.count(), 2);
  assert.equal(await background(previews.nth(0)), 'rgb(243, 244, 239)');
  assert.equal(await background(previews.nth(1)), 'rgb(23, 29, 24)');
  await snapshot('workbench-compare.png');
  await page.getByLabel('Compare light & dark').uncheck();
  await page.getByLabel('Density', { exact: true }).selectOption('compact');
  assert.equal(await primary.evaluate(el => getComputedStyle(el).minHeight), '36px');
  await page.getByLabel('Palette', { exact: true }).selectOption('custom');
  await page.getByLabel('Primary', { exact: true }).fill('#2458a6');
  assert.equal(await background(primary), 'rgb(36, 88, 166)');
  await page.getByLabel('Appearance', { exact: true }).selectOption('system');
  await page.getByLabel('Palette', { exact: true }).selectOption('forest');
  await page.emulateMedia({ colorScheme: 'dark', reducedMotion: 'reduce' });
  assert.equal(await background(page.locator('.preview')), 'rgb(23, 29, 24)');
  assert.equal(await primary.evaluate(el => getComputedStyle(el).transitionDuration.split(',').every(duration => duration.trim() === '0s')), true);
  await primary.hover();
  assert.equal(await primary.evaluate(el => getComputedStyle(el).translate), '0px');
  assert.equal(await page.locator('.aar-enter').first().evaluate(el => getComputedStyle(el).animationName), 'none');
  await page.getByRole('button', { name: 'Components', exact: true }).click();
  const action = page.getByRole('button', { name: 'Primary action', exact: true });
  await action.focus();
  await page.keyboard.press('Tab');
  const focus = await page.locator(':focus').evaluate(el => ({ name: el.textContent, style: getComputedStyle(el).outlineStyle }));
  assert.equal(focus.name, 'Secondary');
  assert.equal(focus.style, 'solid');
  assert.equal(await page.getByRole('button', { name: 'Unavailable' }).isDisabled(), true);
  await page.getByRole('button', { name: 'Replay motion' }).click();
  assert.equal(await page.locator('.motion-study .aar-enter').count(), 3);
  assert.equal(await page.locator('.motion-study .aar-enter').last().evaluate(el => getComputedStyle(el).animationName), 'none');
  await page.emulateMedia({ reducedMotion: 'no-preference' });
  await page.getByRole('button', { name: 'Replay motion' }).click();
  assert.equal(await page.locator('.motion-study .aar-enter').last().evaluate(el => getComputedStyle(el).animationDelay), '0.07s');
  await page.emulateMedia({ reducedMotion: 'reduce' });
  await snapshot('components-dark.png');
  for (const view of ['Workbench', 'Components', 'Design lessons']) {
    await page.getByRole('button', { name: view, exact: true }).click();
    await page.setViewportSize({ width: 390, height: 844 });
    assert.equal(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), true, `${view} mobile overflow`);
    await snapshot(`${view.toLowerCase().replaceAll(' ', '-')}-mobile.png`);
  }
  await page.getByRole('link', { name: 'Contextual Empty', exact: true }).click();
  await page.getByRole('heading', { name: 'Contextual Empty', exact: true }).waitFor();
  await page.getByRole('button', { name: 'Search', exact: true }).click();
  await page.getByRole('button', { name: 'Clear search', exact: true }).click();
  assert.match(await page.getByRole('status').textContent(), /Clear-search action received/);
  await page.reload();
  await page.getByRole('heading', { name: 'Contextual Empty', exact: true }).waitFor();
  assert.equal(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), true, 'Contextual Empty mobile overflow');
  await snapshot('contextual-empty-mobile.png');
  await page.getByRole('link', { name: 'Overview', exact: true }).click();
  await page.getByRole('heading', { name: 'TechAaroorian UI', exact: true }).waitFor();
  assert.equal(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), true, 'Collection mobile overflow');
  await snapshot('collection-mobile.png');
  await page.getByRole('link', { name: 'Icons', exact: true }).click();
  await page.getByRole('heading', { name: 'Lucide icons', exact: true }).waitFor();
  await page.getByRole('button', { name: 'Open settings', exact: true }).click();
  assert.match(await page.getByRole('status').textContent(), /Settings action received/);
  assert.equal(await page.getByRole('button', { name: 'Open settings' }).locator('svg').getAttribute('aria-hidden'), 'true');
  assert.equal(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), true, 'Icon guide mobile overflow');
  await snapshot('icons-mobile.png');
  await page.getByRole('link', { name: 'Versioning', exact: true }).click();
  await page.getByRole('heading', { name: 'Versions & releases', exact: true }).waitFor();
  await page.reload();
  await page.getByRole('heading', { name: 'Versions & releases', exact: true }).waitFor();
  assert.equal(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), true, 'Version guide mobile overflow');
  await page.getByRole('link', { name: 'Headless', exact: true }).click();
  await page.getByRole('heading', { name: 'Headless building blocks', exact: true }).waitFor();
  await page.getByRole('button', { name: 'Duplicate selected', exact: true }).click();
  await page.getByRole('button', { name: 'Cover copy', exact: true }).waitFor();
  assert.equal(await page.getByRole('button', { name: 'Cover copy', exact: true }).getAttribute('aria-pressed'), 'true');
  await page.getByRole('button', { name: 'Remove selected', exact: true }).click();
  assert.equal(await page.getByRole('button', { name: 'Details', exact: true }).getAttribute('aria-pressed'), 'true');
  await page.getByRole('button', { name: 'Move selected to start', exact: true }).click();
  assert.equal(await page.locator('[aria-label="Collection items"] button').first().textContent(), 'Details');
  await page.getByLabel('Choose images').setInputFiles({ name: 'cover.png', mimeType: 'image/png', buffer: Buffer.from('example') });
  assert.match(await page.locator('#intake-result').textContent(), /Accepted 1 file/);
  await page.getByLabel('Choose images').setInputFiles({ name: 'oversize.png', mimeType: 'image/png', buffer: Buffer.alloc(2 * 1024 * 1024 + 1) });
  assert.match(await page.locator('#intake-result').textContent(), /exceeds/);
  await page.getByRole('button', { name: 'Clear file result', exact: true }).click();
  assert.match(await page.locator('#intake-result').textContent(), /No files selected/);
  assert.equal(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), true, 'Headless guide mobile overflow');
  await snapshot('headless-mobile.png');
  assert.deepEqual(errors, []);
  console.log('Visual smoke passed: interactions, nested themes, custom colors, system dark, density, focus, reduced motion, and mobile overflow. Screenshots: apps/docs/visual-artifacts/');
} finally { await browser.close(); }
